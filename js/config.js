/* ───────── 사당 둘레 완충 구간 (blend) ─────────
   사당 자리는 hAt() 에서 gy 높이로 평탄화된다. 그 평지와 바깥 지형을
   smoothstep 으로 잇는데, smoothstep 이 만드는 최대 기울기는
        1.5 · |Δh| / (outer - inner)
   이다. 걷기 한계는 1.5 이므로 폭을 좁게 잡으면 사당 둘레에 넘을 수 없는
   "턱"이 생긴다 — 사당이 눈앞에 보이는데 올라갈 수 없다.
   (태양열이 7~15m 폭에서, 수력이 9~30m 폭에서 실제로 이 함정에 빠졌다.)
   그래서 폭을 고정하지 않고, 사당마다 둘레 지형과의 높이차 Δh 를 재서
   블렌드 기울기가 0.55 를 넘지 않도록 넓힌다.
   단 이웃 사당과 완충 구간이 겹치면 두 블렌드가 서로를 밀어 오히려
   울퉁불퉁해지므로, 이웃까지 거리의 0.55 배로 상한을 둔다.
   ※ 사당 좌표나 지형을 바꾸면 이 값은 자동으로 다시 계산된다. */
